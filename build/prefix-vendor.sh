#!/usr/bin/env bash
# Regenerates vendor-prefixed/ (A103): the runtime libraries bacon/bacon-qr-code and dasprid/enum copied
# with Strauss into the namespace PassCaptain\Vendor\ (BaconQrCode\ -> PassCaptain\Vendor\BaconQrCode\,
# DASPRiD\Enum\ -> PassCaptain\Vendor\DASPRiD\Enum\), so another plugin that ships its own (other) version
# of these libraries or of endroid/qr-code can never collide with the plugin's copy.
#
#   bash build/prefix-vendor.sh           regenerate vendor-prefixed/ (commit the result)
#   bash build/prefix-vendor.sh --check   fail when the committed vendor-prefixed/ differs from a fresh run
#                                         (CI job "static"); nothing in the working tree is changed
#
# - vendor-prefixed/ is committed: the release build (build/release.sh, `composer install --no-dev
#   --no-scripts --no-plugins`) does not run Strauss and only ships the prefixed copy. The original
#   packages are dev dependencies (composer.json require-dev) and never reach the ZIP.
# - The prefixed classes are loaded by the plugin's Composer autoloader (composer.json autoload.classmap).
# - Needs a full development install (composer install) because Strauss copies from vendor/.
# - Strauss is a pinned PHAR, verified by its SHA-256 before it runs (supply chain, no Composer plugin).
# - Strauss settings: composer.json extra.strauss. Update procedure: docs/OPERATIONS.md, "Präfixierte
#   Bibliotheken aktualisieren".
set -euo pipefail
export LC_ALL=C TZ=UTC
umask 022

STRAUSS_VERSION="0.31.1"
STRAUSS_SHA256="17dc2baf27b9a3f52834e3db729c8365d8915a80e37a087d253cf705387aa887"
STRAUSS_URL="https://github.com/BrianHenryIE/strauss/releases/download/${STRAUSS_VERSION}/strauss.phar"

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TARGET="vendor-prefixed"
MODE="write"
[ "${1:-}" = "--check" ] && MODE="check"

for pkg in bacon/bacon-qr-code dasprid/enum; do
	[ -f "${ROOT}/vendor/${pkg}/composer.json" ] || { echo "vendor/${pkg} is missing – run composer install (with dev dependencies) first." >&2; exit 1; }
done

CACHE="${WPCAP_STRAUSS_CACHE:-${ROOT}/build/.strauss}"
PHAR="${CACHE}/strauss-${STRAUSS_VERSION}.phar"
mkdir -p "${CACHE}"
if [ ! -f "${PHAR}" ] || [ "$(sha256sum "${PHAR}" | cut -d' ' -f1)" != "${STRAUSS_SHA256}" ]; then
	curl -fsSL --retry 3 -o "${PHAR}.part" "${STRAUSS_URL}"
	mv "${PHAR}.part" "${PHAR}"
fi
echo "${STRAUSS_SHA256}  ${PHAR}" | sha256sum -c --quiet - || { rm -f "${PHAR}"; echo "Strauss PHAR checksum mismatch – refusing to run it." >&2; exit 1; }

# Strauss runs in a scratch project (composer.json + vendor/ of this checkout) so --check never touches
# the working tree and a failed run never leaves a half-written vendor-prefixed/ behind.
WORK="$(mktemp -d "${TMPDIR:-/tmp}/wpcap-strauss.XXXXXX")"
trap 'rm -rf "${WORK}"' EXIT
cp "${ROOT}/composer.json" "${ROOT}/composer.lock" "${WORK}/"
ln -s "${ROOT}/vendor" "${WORK}/vendor"
(cd "${WORK}" && php "${PHAR}" --silent)

OUT="${WORK}/${TARGET}"
[ -f "${OUT}/bacon/bacon-qr-code/src/Encoder/Encoder.php" ] || { echo "Strauss did not produce ${TARGET}/bacon/bacon-qr-code." >&2; exit 1; }

# Deterministic output: Composer's installed.json depends on how the packages were installed (dist or
# source); it is replaced by a short manifest (name, version, commit, licence) that tests compare with
# composer.lock. Markdown files are not shipped anyway (.distignore).
php -r '
$in  = json_decode( (string) file_get_contents( $argv[1] ), true );
$out = array();
foreach ( $in["packages"] ?? $in as $p ) {
	$out[] = array( "name" => $p["name"], "version" => $p["version"], "reference" => $p["dist"]["reference"] ?? ( $p["source"]["reference"] ?? "" ), "license" => $p["license"] ?? array() );
}
usort( $out, static fn( $a, $b ) => strcmp( $a["name"], $b["name"] ) );
file_put_contents( $argv[2], json_encode( array( "_comment" => "Generated by build/prefix-vendor.sh (Strauss, namespace prefix PassCaptain\\Vendor\\). Do not edit.", "packages" => $out ), JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES ) . "\n" );
' "${OUT}/composer/installed.json" "${OUT}/manifest.json"
rm -rf "${OUT}/composer"
find "${OUT}" -name '*.md' -type f -delete
for pkg in bacon/bacon-qr-code dasprid/enum; do
	[ -f "${OUT}/${pkg}/LICENSE" ] || cp "${ROOT}/vendor/${pkg}/LICENSE" "${OUT}/${pkg}/LICENSE"
done
# Leftover unprefixed references would load the global (possibly foreign) classes again.
if grep -rnE '(^|[^\\A-Za-z_])\\?(BaconQrCode|DASPRiD)\\[A-Z]' --include='*.php' "${OUT}" | grep -v 'PassCaptain\\Vendor\\' ; then
	echo "Unprefixed BaconQrCode/DASPRiD references left in ${TARGET}/ (see above)." >&2
	exit 1
fi

if [ "${MODE}" = "check" ]; then
	if ! diff -r "${OUT}" "${ROOT}/${TARGET}" >"${WORK}/diff.txt" 2>&1; then
		head -n 60 "${WORK}/diff.txt" >&2
		echo "${TARGET}/ is out of date with composer.lock / composer.json extra.strauss: run bash build/prefix-vendor.sh and commit the result." >&2
		exit 1
	fi
	echo "${TARGET}/ matches a fresh Strauss run (Strauss ${STRAUSS_VERSION})."
	exit 0
fi

rm -rf "${ROOT:?}/${TARGET}"
cp -R "${OUT}" "${ROOT}/${TARGET}"
echo "Regenerated ${TARGET}/ with Strauss ${STRAUSS_VERSION}. Next: composer dump-autoload, run the tests, commit ${TARGET}/."
